import { CartItem } from '../../context/CartContext';
import { formatINR } from '../../utils/currency';

export interface SandboxCustomerInfo {
  fullName: string;
  email: string;
  country: string;
  organization?: string;
}

export type SandboxPaymentMethod = 'test_upi' | 'test_card' | 'test_netbanking';

export interface SandboxOrder {
  id: string;
  createdAt: string;
  customer: SandboxCustomerInfo;
  items: CartItem[];
  subtotalPaise: number;
  subtotalFormatted: string;
  paymentMethod: SandboxPaymentMethod;
  isSandboxOrder: true;
  downloadAccessTokens: Record<string, string>;
}

const ORDERS_STORAGE_KEY = 'digiecom_orders_v1';

/**
 * Client-Side Sandbox Checkout & Order Simulation Service
 *
 * Provides a 100% transparent test environment for evaluating the checkout
 * user experience without processing real payments or collecting sensitive data.
 */
export class SandboxCheckoutService {
  /**
   * Generates a realistic mock order ID.
   */
  public static generateOrderId(): string {
    const randomHex = Math.random().toString(36).substring(2, 7).toUpperCase();
    return `DIGI-SBX-${randomHex}`;
  }

  /**
   * Creates and persists a simulated order in localStorage.
   */
  public static createOrder(
    customer: SandboxCustomerInfo,
    items: CartItem[],
    subtotalPaise: number,
    paymentMethod: SandboxPaymentMethod
  ): SandboxOrder {
    const orderId = this.generateOrderId();
    const now = new Date().toISOString();

    // Generate mock access tokens for each product deliverable
    const downloadAccessTokens: Record<string, string> = {};
    for (const item of items) {
      downloadAccessTokens[item.product.id] = `token-sbx-${item.product.id}-${Date.now().toString(36)}`;
    }

    const order: SandboxOrder = {
      id: orderId,
      createdAt: now,
      customer,
      items,
      subtotalPaise,
      subtotalFormatted: formatINR(subtotalPaise),
      paymentMethod,
      isSandboxOrder: true,
      downloadAccessTokens,
    };

    // Save to local storage history
    this.saveOrderToHistory(order);

    return order;
  }

  /**
   * Retrieves all previous sandbox orders from localStorage.
   */
  public static getOrderHistory(): SandboxOrder[] {
    if (typeof window === 'undefined') return [];
    try {
      const raw = window.localStorage.getItem(ORDERS_STORAGE_KEY);
      if (!raw) return [];
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }

  /**
   * Appends an order to history safely.
   */
  public static saveOrderToHistory(order: SandboxOrder): void {
    if (typeof window === 'undefined') return;
    try {
      const history = this.getOrderHistory();
      const updated = [order, ...history].slice(0, 20); // Keep last 20
      window.localStorage.setItem(ORDERS_STORAGE_KEY, JSON.stringify(updated));
    } catch (err) {
      console.warn('Failed to save sandbox order to history:', err);
    }
  }

  /**
   * Generates a safe simulated file download in the browser.
   * Downloads a structured text document containing the product details,
   * simulated license key, and documentation inclusions.
   */
  public static triggerSimulatedDownload(productName: string, productId: string, formats: string[]): void {
    if (typeof window === 'undefined' || typeof document === 'undefined') return;

    const content = [
      '========================================================================',
      `DIGIECOM DIGITAL PRODUCTS — SIMULATED DEMO DELIVERABLE`,
      '========================================================================',
      `Product:      ${productName}`,
      `Product ID:   ${productId}`,
      `Formats:      ${formats.join(', ')}`,
      `License Type: Commercial Single-Project License (Demonstration)`,
      `Generated At: ${new Date().toLocaleString()}`,
      '',
      'NOTE: This is a safe simulated digital asset download generated by the',
      'DigiEcom sandbox checkout simulator. In production, real digital assets',
      '(.zip archives, .fig files, .pdf e-books) are served via cryptographically',
      'signed, short-lived CDN URLs (Cloudflare R2 / AWS S3) upon payment webhook confirmation.',
      '',
      '--- INCLUDED PACKAGE MANIFEST ---',
      '1. README.md — Setup & Quickstart Guide',
      '2. LICENSE.txt — Terms of usage and redistribution limits',
      '3. ASSETS_INDEX.json — Cryptographic checksums and version metadata',
      '========================================================================',
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${productName.toLowerCase().replace(/[^a-z0-9]/g, '-')}-demo-package.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }
}
